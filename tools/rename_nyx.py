#!/usr/bin/env python3
"""Rename Nixe to Nyx in one checkout: file contents and file names.

    tools/rename_nyx.py ~/Projects/nixe-core            # dry run: what would change
    tools/rename_nyx.py --apply ~/Projects/nixe-core    # rewrite files, `git mv` renamed paths

Only tracked text files are touched. Files with uncommitted changes are reported and
left alone, unless --dirty: then the committed version is renamed in the index and the
working copy on disk, so a commit takes only the rename. Lockfiles (regenerated by
cargo) and historical records are never changed. Plan: docs/RENAME_NYX.md.
"""

import argparse
import re
import subprocess
import sys
from pathlib import Path

# "nixe" at the start of a word or after a separator, in each casing. A letter
# before it means another word ("unixepoch").
WORD = re.compile(r"(?<![A-Za-z])(NIXE|Nixe|nixe)")
NEW = {"NIXE": "NYX", "Nixe": "Nyx", "nixe": "nyx"}

# Never rewritten: regenerated, or records of what happened under the old name.
SKIP = (
    re.compile(r"(^|/)Cargo\.lock$"),
    re.compile(r"(^|/)package-lock\.json$"),
    re.compile(r"^MULTIREPO_MIGRATION\.md$"),
    re.compile(r"^docs/migration/"),
    re.compile(r"^docs/RENAME_NYX\.md$"),
    re.compile(r"^tools/rename_nyx\.py$"),
    re.compile(r"^tools/migrate_desktop\.py$"),
)


def git(repo, *args):
    return subprocess.run(["git", "-C", str(repo), *args], check=True, capture_output=True, text=True).stdout


def rename(text):
    return WORD.sub(lambda m: NEW[m.group(1)], text)


def rename_staged(repo, f):
    """Rename the committed text of `f` in the index, leaving the working copy's own changes unstaged."""
    old = subprocess.run(["git", "-C", str(repo), "show", f"HEAD:{f}"], check=True, capture_output=True).stdout
    blob = subprocess.run(
        ["git", "-C", str(repo), "hash-object", "-w", "--stdin"], input=rename(old.decode()).encode(),
        check=True, capture_output=True,
    ).stdout.decode().strip()
    mode = git(repo, "ls-files", "-s", "--", f).split()[0]
    git(repo, "update-index", "--cacheinfo", f"{mode},{blob},{f}")


def plan(repo, dirty_ok=False):
    files = [f for f in git(repo, "ls-files", "-z").split("\0") if f]
    dirty = {line[3:] for line in git(repo, "status", "--porcelain").splitlines()}
    edits, moves, held = {}, {}, []
    staged = set()
    for f in files:
        if any(p.search(f) for p in SKIP):
            # Never rewritten, but moved along with a renamed folder.
            if rename(f) != f and f not in dirty:
                moves[f] = rename(f)
            continue
        path = repo / f
        if path.is_symlink() or not path.is_file():
            continue
        data = path.read_bytes()
        if b"\0" in data[:8192]:
            text = None
        else:
            try:
                text = data.decode()
            except UnicodeDecodeError:
                text = None
        changed = text is not None and WORD.search(text)
        target = rename(f)
        if not changed and target == f:
            continue
        if f in dirty and not (dirty_ok and (repo / f).exists()):
            held.append(f)
            continue
        if changed:
            edits[f] = (text, rename(text))
            if f in dirty:
                staged.add(f)
        if target != f:
            moves[f] = target
    return edits, moves, held, staged


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("repos", nargs="+", type=Path)
    ap.add_argument("--apply", action="store_true", help="write the changes (default: dry run)")
    ap.add_argument("--dirty", action="store_true", help="also rename files with uncommitted changes")
    ap.add_argument("-v", "--verbose", action="store_true", help="list every changed line")
    args = ap.parse_args()
    for repo in args.repos:
        repo = repo.expanduser().resolve()
        edits, moves, held, staged = plan(repo, args.dirty)
        lines = sum(sum(a != b for a, b in zip(old.splitlines(), new.splitlines())) for old, new in edits.values())
        print(f"{repo.name}: {len(edits)} files, {lines} lines, {len(moves)} renames, {len(held)} held back")
        for f in held:
            print(f"  held (uncommitted changes): {f}")
        for f in sorted(staged):
            print(f"  renamed around uncommitted changes: {f}")
        if args.verbose:
            for f, (old, new) in edits.items():
                for n, (a, b) in enumerate(zip(old.splitlines(), new.splitlines()), 1):
                    if a != b:
                        print(f"  {f}:{n}: {b.strip()[:160]}")
            for f, t in moves.items():
                print(f"  mv {f} -> {t}")
        if not args.apply:
            continue
        for f in staged:
            rename_staged(repo, f)
        for f, (_, new) in edits.items():
            (repo / f).write_text(new)
        for f, t in sorted(moves.items()):
            (repo / t).parent.mkdir(parents=True, exist_ok=True)
            git(repo, "mv", f, t)
        # Folders emptied by the moves.
        for f in sorted(moves, key=lambda p: -p.count("/")):
            d = (repo / f).parent
            while d != repo and d.is_dir() and not any(d.iterdir()):
                d.rmdir()
                d = d.parent
    return 0


if __name__ == "__main__":
    sys.exit(main())
